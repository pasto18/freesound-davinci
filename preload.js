const { contextBridge, ipcRenderer } = require('electron/renderer');

contextBridge.exposeInMainWorld('api', {
    getStatus: () => ipcRenderer.invoke('app:status'),
    checkUpdate: () => ipcRenderer.invoke('update:check'),
    applyUpdate: () => ipcRenderer.invoke('update:apply'),
    restartApp: () => ipcRenderer.invoke('update:restart'),
    login: () => ipcRenderer.invoke('fs:login'),
    logout: () => ipcRenderer.invoke('fs:logout'),
    search: (opts) => ipcRenderer.invoke('fs:search', opts),
    localSearch: (opts) => ipcRenderer.invoke('local:search', opts),
    localRead: (rel) => ipcRenderer.invoke('local:read', rel),
    giphySearch: (opts) => ipcRenderer.invoke('giphy:search', opts),
    configGet: () => ipcRenderer.invoke('config:get'),
    configSet: (values) => ipcRenderer.invoke('config:set', values),
    ytSearch: (opts) => ipcRenderer.invoke('yt:search', opts),
    ytStream: (opts) => ipcRenderer.invoke('yt:stream', opts),
    ytExists: (opts) => ipcRenderer.invoke('yt:exists', opts),
    ytDownload: (opts) => ipcRenderer.invoke('yt:download', opts),
    ytCancel: (job) => ipcRenderer.invoke('yt:cancel', job),
    onYtPartial: (cb) => ipcRenderer.on('yt:partial', (e, p) => cb(p)),
    onYtProgress: (cb) => ipcRenderer.on('yt:progress', (e, p) => cb(p)),
    elevenVoices: () => ipcRenderer.invoke('eleven:voices'),
    elevenAddVoice: (opts) => ipcRenderer.invoke('eleven:addVoice', opts),
    elevenRemoveVoice: (id) => ipcRenderer.invoke('eleven:removeVoice', id),
    elevenModels: () => ipcRenderer.invoke('eleven:models'),
    elevenTts: (opts) => ipcRenderer.invoke('eleven:tts', opts),
    elevenSfx: (opts) => ipcRenderer.invoke('eleven:sfx', opts),
    elevenList: () => ipcRenderer.invoke('eleven:list'),
    fontsSearch: (opts) => ipcRenderer.invoke('fonts:search', opts),
    fontsInstall: (opts) => ipcRenderer.invoke('fonts:install', opts),
    fontsApply: (opts) => ipcRenderer.invoke('fonts:apply', opts),
    svgSearch: (opts) => ipcRenderer.invoke('svg:search', opts),
    svgText: (file) => ipcRenderer.invoke('svg:text', file),
    svgSavePng: (file, dataUrl) => ipcRenderer.invoke('svg:savePng', file, dataUrl),
    download: (sound) => ipcRenderer.invoke('fs:download', sound),
    insert: (sound, trackIndex, clipFile) => ipcRenderer.invoke('resolve:insert', sound, trackIndex, clipFile),
    clipRead: (file) => ipcRenderer.invoke('clip:read', file),
    clipSave: (name, bytes) => ipcRenderer.invoke('clip:save', name, bytes),
    clipExists: (name) => ipcRenderer.invoke('clip:exists', name),
    startDrag: (file) => ipcRenderer.send('drag:start', file),
    cleanup: () => ipcRenderer.invoke('resolve:cleanup')
});
